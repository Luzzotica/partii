// Generate everything that follows from api/openapi.yaml:
//   edge/src/generated/routes.ts       the edge's route table (method, path, auth)
//   crates/partii-api/src/generated.rs the operation table the Rust client and CLI use
//   sdk/ts/src/generated.ts            a typed fetch client for web apps
//   docs/API.md                        the reference
// Run: node api/gen.mjs   (CI checks the outputs are current: --check)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "edge/package.json"));
const yaml = require("js-yaml");
const spec = yaml.load(readFileSync(join(root, "api/openapi.yaml"), "utf8"));
const check = process.argv.includes("--check");

const ops = [];
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(methods)) {
    const params = (op.parameters ?? []).map((p) => ({ name: p.name, in: p.in, required: !!p.required, type: p.schema?.type ?? "string" }));
    const body = op["x-body"] === "binary" ? "binary" : op.requestBody ? "json" : "none";
    const bodySchema = op.requestBody?.content?.["application/json"]?.schema;
    let fields = [];
    if (bodySchema?.properties) fields = Object.entries(bodySchema.properties).map(([k, v]) => ({ name: k, type: v.type ?? "any", required: (bodySchema.required ?? []).includes(k) }));
    if (bodySchema?.$ref) {
      const s = spec.components.schemas[bodySchema.$ref.split("/").pop()];
      fields = Object.entries(s.properties).map(([k, v]) => ({ name: k, type: Array.isArray(v.type) ? v.type[0] : v.type ?? "any", required: false }));
    }
    ops.push({
      id: op.operationId,
      method: method.toUpperCase(),
      path,
      auth: op["x-auth"],
      cli: op["x-cli"] ?? null,
      summary: op.summary ?? "",
      params,
      body,
      fields,
      response: op["x-response"] === "binary" ? "binary" : "json",
    });
  }
}
const ids = new Set();
for (const o of ops) {
  if (ids.has(o.id)) throw new Error(`duplicate operationId ${o.id}`);
  ids.add(o.id);
  if (!["public", "key", "player", "developer", "admin", "stripe"].includes(o.auth)) throw new Error(`${o.id}: bad x-auth ${o.auth}`);
}

const banner = "// Generated by api/gen.mjs from api/openapi.yaml. Do not edit.\n";
const outputs = {};

// ── Edge route table ──
outputs["edge/src/generated/routes.ts"] =
  banner +
  `export type Auth = "public" | "key" | "player" | "developer" | "admin" | "stripe";\n` +
  `export interface Route { op: string; method: string; path: string; auth: Auth; body: "none" | "json" | "binary" }\n` +
  `export const ROUTES: Route[] = ${JSON.stringify(
    ops.map((o) => ({ op: o.id, method: o.method, path: o.path.replace(/\{(\w+)\}/g, ":$1"), auth: o.auth, body: o.body })),
    null,
    2,
  )};\n`;

// ── Rust operation table ──
const rs = (s) => JSON.stringify(s);
const rsParams = (ps) => `&[${ps.map((p) => `Param { name: ${rs(p.name)}, loc: ${p.in === "path" ? "Loc::Path" : "Loc::Query"}, required: ${p.required} }`).join(", ")}]`;
const rsFields = (fs) => `&[${fs.map((f) => `Field { name: ${rs(f.name)}, ty: ${rs(f.type)}, required: ${f.required} }`).join(", ")}]`;
outputs["crates/partii-api/src/generated.rs"] =
  banner +
  `use crate::{Auth, Body, Field, Loc, Op, Param};\n\n/// Every operation in api/openapi.yaml.\npub const OPS: &[Op] = &[\n` +
  ops
    .map(
      (o) =>
        `    Op { id: ${rs(o.id)}, method: ${rs(o.method)}, path: ${rs(o.path)}, auth: Auth::${o.auth[0].toUpperCase() + o.auth.slice(1)}, cli: ${o.cli ? `Some(${rs(o.cli)})` : "None"}, summary: ${rs(o.summary)}, params: ${rsParams(o.params)}, body: Body::${o.body[0].toUpperCase() + o.body.slice(1)}, fields: ${rsFields(o.fields)}, binary_response: ${o.response === "binary"} },`,
    )
    .join("\n") +
  `\n];\n`;

// ── TypeScript client ──
const camel = (s) => s;
outputs["sdk/ts/src/generated.ts"] =
  banner +
  `import type { Transport } from "./client";\n\n` +
  `export function operations(t: Transport) {\n  return {\n` +
  ops
    .filter((o) => o.auth !== "stripe")
    .map((o) => {
      const pathParams = o.params.filter((p) => p.in === "path").map((p) => p.name);
      const query = o.params.filter((p) => p.in === "query").map((p) => p.name);
      const args = [...pathParams.map((p) => `${p}: string`)];
      if (query.length) args.push(`query: { ${query.map((q) => `${q}?: string | number`).join("; ")} } = {}`);
      if (o.body === "json") args.push(`body: Record<string, unknown> = {}`);
      if (o.body === "binary") args.push(`body: BodyInit`);
      const pathExpr = "`" + o.path.replace(/\{(\w+)\}/g, "${encodeURIComponent($1)}") + "`";
      return `    /** ${o.summary} (${o.auth}) */\n    ${camel(o.id)}: (${args.join(", ")}) => t.call(${rs(o.method)}, ${pathExpr}, ${rs(o.auth)}, ${query.length ? "query" : "{}"}, ${o.body === "none" ? "undefined" : "body"}, ${rs(o.response)}),`;
    })
    .join("\n") +
  `\n  };\n}\n`;

// ── Docs ──
let md = `# partii API reference\n\nGenerated from \`api/openapi.yaml\` by \`api/gen.mjs\`. ${spec.info.description.split("\n")[0]}\n\n`;
md += spec.info.description.split("\n").slice(1).join("\n") + "\n\n";
md += "| Operation | Method and path | Auth | CLI |\n|---|---|---|---|\n";
for (const o of ops) md += `| \`${o.id}\` | \`${o.method} ${o.path}\` | ${o.auth} | ${o.cli ? `\`partii ${o.cli}\`` : "–"} |\n`;
md += "\n## Operations\n";
for (const o of ops) {
  md += `\n### ${o.id}\n\n\`${o.method} ${o.path}\` (auth: ${o.auth})${o.cli ? ` · \`partii ${o.cli}\`` : ""}\n\n${o.summary}\n`;
  const ps = o.params.map((p) => `- \`${p.name}\` (${p.in}${p.required ? ", required" : ""})`);
  if (ps.length) md += `\nParameters:\n${ps.join("\n")}\n`;
  if (o.body === "binary") md += `\nBody: the file's bytes.\n`;
  if (o.fields.length) md += `\nBody fields: ${o.fields.map((f) => `\`${f.name}\`${f.required ? " (required)" : ""}`).join(", ")}\n`;
}
outputs["docs/API.md"] = md;

let stale = [];
for (const [rel, text] of Object.entries(outputs)) {
  const p = join(root, rel);
  const old = existsSync(p) ? readFileSync(p, "utf8") : null;
  if (old === text) continue;
  if (check) stale.push(rel);
  else {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, text);
  }
}
if (check && stale.length) {
  console.error(`out of date (run node api/gen.mjs): ${stale.join(", ")}`);
  process.exit(1);
}
console.log(JSON.stringify({ ok: true, operations: ops.length, wrote: check ? [] : Object.keys(outputs) }));
